# Esse código tem como objetivo ler valores inteiros imputados pelo usuário e calcular a diferença

# Ler os valores inteiros fornecidos pelo usuário
A = int(input("Digite o valor de A: "))
B = int(input("Digite o valor de B: "))
C = int(input("Digite o valor de C: "))
D = int(input("Digite o valor de D: "))

# Calculo da diferença
DIFERENCA = (A * B) - (C * D)

# Exibir resultados
print("A fórmula para a diferença é (A * B) - (C * D)")
printf("Substituindo os valores fornecidos ({A} * {B}) - ({C} * {D}) ")
print(DIFERENCA)